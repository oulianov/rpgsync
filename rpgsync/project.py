"""An RPG Maker 2000/2003 project folder and its script folder."""

from __future__ import annotations

import configparser
import glob
import hashlib
import json
import os
import re

from . import scriptfiles
from .commands import Ctx
from .lcf import LcfError, LcfFile, read_map_tree_names

# Windows code pages used by RPG Maker games, as Python codec names.
CODEPAGES = {
    "932": "cp932",
    "936": "gbk",
    "949": "cp949",
    "950": "cp950",
    "1250": "cp1250",
    "1251": "cp1251",
    "1252": "cp1252",
    "1253": "cp1253",
    "1254": "cp1254",
    "1255": "cp1255",
    "1256": "cp1256",
    "1257": "cp1257",
    "1258": "cp1258",
    "874": "cp874",
}

CONFIG_DIR = ".rpgsync"


def _stat(path: str) -> tuple[int, int] | None:
    try:
        st = os.stat(path)
    except OSError:
        return None
    return (st.st_mtime_ns, st.st_size)


class Project:
    def __init__(self, game_dir: str, script_dir: str | None = None, encoding: str | None = None):
        self.game_dir = os.path.abspath(game_dir)
        if not os.path.exists(os.path.join(self.game_dir, "RPG_RT.ldb")):
            raise SystemExit("%s is not an RPG Maker 2000/2003 project (no RPG_RT.ldb)" % self.game_dir)
        self.script_dir = os.path.abspath(script_dir or os.path.join(self.game_dir, "Scripts"))
        self.state_dir = os.path.join(self.script_dir, CONFIG_DIR)
        # nothing is written until the first sync: reading a game never creates its scripts folder
        self._pending_config: dict | None = None
        cfg = self._load_config()
        self.encoding = encoding or cfg.get("encoding") or self.detect_encoding()
        "x".encode(self.encoding)  # validate codec name early
        if cfg.get("encoding") != self.encoding:
            cfg["encoding"] = self.encoding
            self._store_config(cfg)
        self._ctx: Ctx | None = None
        self._ldb_stat: tuple[int, int] | None = None
        self._handles_key: tuple | None = None
        self._map_names: tuple[tuple | None, dict[int, bytes]] = (None, {})  # RPG_RT.lmt stat -> raw names
        names = os.path.join(self.script_dir, "database", "names.py")  # generated by an older rpgsync
        if os.path.exists(names):
            with open(names, encoding="utf-8") as f:
                if "(generated by rpgsync from RPG_RT.ldb, do not edit)" in f.readline():
                    os.remove(names)
        old = os.path.join(self.script_dir, "CommonEvents.py")  # before rpgsync put it in database/
        if os.path.exists(old) and not scriptfiles.exists(self.common_events_script):
            os.makedirs(os.path.dirname(self.common_events_script), exist_ok=True)
            os.replace(old, self.common_events_script)

    # -- paths ---------------------------------------------------------------
    @property
    def ldb_path(self) -> str:
        return os.path.join(self.game_dir, "RPG_RT.ldb")

    def map_paths(self) -> dict[int, str]:
        out = {}
        for p in glob.glob(os.path.join(self.game_dir, "*")):
            m = re.fullmatch(r"map(\d{4})\.lmu", os.path.basename(p), re.I)
            if m:
                out[int(m.group(1))] = p
        return dict(sorted(out.items()))

    def script_for_map(self, map_id: int) -> str:
        """Its path as one file: Map0001.py (Map0001/ when split in files)."""
        return os.path.join(self.script_dir, "Map%04d.py" % map_id)

    def map_scripts(self) -> list[int]:
        """The ids of the map scripts of the scripts folder (MapNNNN.py, MapNNNN/)."""
        try:
            names = os.listdir(self.script_dir)
        except OSError:
            return []
        out = set()
        for name in names:
            m = re.fullmatch(r"Map(\d{4})(\.py)?", name)
            if m and (m.group(2) or scriptfiles.is_package(os.path.join(self.script_dir, name + ".py"))):
                out.add(int(m.group(1)))
        return sorted(out)

    @property
    def common_events_script(self) -> str:
        return os.path.join(self.script_dir, "database", "common_events.py")

    @property
    def troop_events_script(self) -> str:
        return os.path.join(self.script_dir, "database", "troop_events.py")

    @property
    def lmt_path(self) -> str:
        return os.path.join(self.game_dir, "RPG_RT.lmt")

    @property
    def map_tree_script(self) -> str:
        return os.path.join(self.script_dir, "database", "map_tree.py")

    # -- config ----------------------------------------------------------------
    def _load_config(self) -> dict:
        if self._pending_config is not None:  # not written yet (no sync so far)
            return dict(self._pending_config)
        try:
            with open(os.path.join(self.state_dir, "config.json")) as f:
                return json.load(f)
        except (OSError, ValueError):
            return {}

    def _store_config(self, cfg: dict) -> None:
        """Save the config, or keep it in memory until the first sync creates the state folder."""
        if os.path.isdir(self.state_dir):
            self._save_config(cfg)
        else:
            self._pending_config = dict(cfg)

    def _save_config(self, cfg: dict) -> None:
        os.makedirs(self.state_dir, exist_ok=True)
        with open(os.path.join(self.state_dir, "config.json"), "w") as f:
            json.dump(cfg, f, indent=2)

    def ensure_state_dir(self) -> None:
        """Create the sync state folder (first write), with the config detected so far."""
        os.makedirs(self.state_dir, exist_ok=True)
        if self._pending_config is not None:
            self._save_config(self._pending_config)
            self._pending_config = None

    # -- encoding ----------------------------------------------------------------
    def detect_encoding(self) -> str:
        ini = os.path.join(self.game_dir, "RPG_RT.ini")
        if os.path.exists(ini):
            cp = configparser.ConfigParser(strict=False, interpolation=None)
            try:
                cp.read(ini, encoding="latin-1")
                for section in ("EasyRPG", "RPG_RT"):
                    if cp.has_option(section, "Encoding"):
                        v = cp.get(section, "Encoding").strip()
                        return CODEPAGES.get(v, v)
            except configparser.Error:
                pass
        # Heuristic: Japanese text decodes as Shift-JIS and contains kana/kanji.
        sample = b""
        lmt = os.path.join(self.game_dir, "RPG_RT.lmt")
        if os.path.exists(lmt):
            sample += b"".join(read_map_tree_names(lmt).values())
        with open(self.ldb_path, "rb") as f:
            sample += f.read(200000)
        nonascii = re.findall(rb"[\x80-\xff][\x40-\xff]", sample)
        if len(nonascii) > 20:
            try:
                text = b"".join(nonascii).decode("cp932")
                jp = sum(1 for ch in text if "぀" <= ch <= "ヿ" or "一" <= ch <= "鿿")
                if jp > len(text) * 0.6:
                    return "cp932"
            except UnicodeDecodeError:
                pass
        return "cp1252"

    # -- database context ----------------------------------------------------------
    def context(self, refresh: bool = False) -> Ctx:
        stat = os.stat(self.ldb_path)
        if (stat.st_mtime_ns, stat.st_size) != self._ldb_stat:
            refresh = True  # changed in the editor or by a sync: names may have changed
            self._ldb_stat = (stat.st_mtime_ns, stat.st_size)
        if self._ctx is None or refresh:
            ctx = Ctx(encoding=self.encoding)
            db = LcfFile.load(self.ldb_path).root
            ctx.engine = "2k3" if (db._chunk(0x1D) is not None or db._chunk(0x1E) is not None) else "2k"
            for key in ("switches", "variables", "items", "actors", "commonevents"):
                ctx.names[key] = {it.id: ctx.dec(it.struct.get("name")) for it in db.get(key) if it.struct.get("name")}
            ctx.choice_sep = self.choice_separator()
            ctx.dynparams = self.has_dynparams()
            self._ctx = ctx
            self._handles_key = None
        # names of variables / switches / maps: the attributes of their database files
        key = (
            *(scriptfiles.stat_key(self.table_script(t)) for t in ("variables", "switches")),
            scriptfiles.stat_key(self.common_events_script),
            _stat(self.map_tree_script),
            _stat(self.lmt_path),
        )
        if key != self._handles_key:
            self._ctx.handles = self._handles(self._ctx)
            self._handles_key = key
        return self._ctx

    def has_dynparams(self) -> bool:
        """Does the game run the DynParams plugin (DynPlugins/DynParams.dll, or listed in
        EasyRPG.ini's [DynRPG] Plugins)?"""
        from . import dynrpg

        return dynrpg.installed(self.game_dir).provides("DynParams.dll")

    def table_sizes(self, tables=("variables", "actors", "items", "skills")) -> dict[str, int]:
        """Entries of database tables: the game's, or the ``size = N`` of their database
        script when it is larger (slots added there, not synced yet)."""
        from .commands import CompileError
        from .database import table_size

        db = LcfFile.load(self.ldb_path).root
        out = {}
        for table in tables:
            out[table] = max((it.id for it in db.get(table)), default=0)
            try:
                text = self._script_text(self.table_script(table), scriptfiles.table_style(table))
                size = table_size(text) if text is not None else None
            except (SyntaxError, ValueError, CompileError):
                size = None  # no script, or one that doesn't compile (reported by check)
            if size is not None:
                out[table] = max(out[table], size.size)
        return out

    def context_signature(self) -> str:
        """What a script compiles against (engine, encoding, names of variables,
        switches and common events...): an unchanged entry compiles the same while this
        stays the same."""
        ctx = self.context()
        key = (ctx.engine, ctx.encoding, ctx.choice_sep, sorted((k, sorted(v.items())) for k, v in ctx.handles.items()))
        if ctx.dynparams:  # (left out otherwise: the signatures of existing states stay valid)
            key += ("dynparams",)
        return hashlib.sha1(repr(key).encode("utf-8")).hexdigest()

    def table_script(self, table: str) -> str:
        return os.path.join(self.script_dir, "database", table + ".py")

    def _handles(self, ctx: Ctx) -> dict[str, dict[int, str]]:
        from .database import identifiers, read_identifiers

        out = {}
        for table in ("variables", "switches"):
            text = self._script_text(self.table_script(table), scriptfiles.table_style(table))
            keep = read_identifiers(text) if text is not None else {}
            # entries of the file count too: a new variable is usable before it reaches the game
            names = {**{n: attr for n, attr in keep.items()}, **ctx.names.get(table, {})}
            out[table] = identifiers(table, names, keep)
        out["common_events"] = self._common_event_names()
        out["maps"] = self._map_handles()
        return out

    @staticmethod
    def _script_text(path: str, style: scriptfiles.Style) -> str | None:
        """A database script's text (joined, when split in files), to read names from;
        None when there is none.  A folder that is not one script yet (reported by the
        sync and check): its files one after the other, so that no name is lost."""
        try:
            return scriptfiles.read_text(path, style)
        except (scriptfiles.LayoutError, scriptfiles.ChangedMeanwhile):
            texts = []
            for p in scriptfiles.paths(path):
                data = scriptfiles.read_bytes(p)
                if data is not None:
                    texts.append(data.decode("utf-8", "replace"))
            return "\n".join(texts) or None
        except (OSError, UnicodeDecodeError):
            return None

    def _map_handles(self) -> dict[int, str]:
        """Attribute names of the maps (``maps.relm``): the ones in map_tree.py, else
        derived from the map tree's names.  Maps of the file not in the game yet count."""
        from .maptree import identifiers, read_identifiers

        try:
            with open(self.map_tree_script, encoding="utf-8") as f:
                keep = read_identifiers(f.read())
        except OSError:
            keep = {}
        names = {**{n: attr for n, attr in keep.items()}, **self.map_names()}
        return identifiers(names, keep)

    def _common_event_names(self) -> dict[int, str]:
        """Function names of the common events: the ones in common_events.py,
        else derived from the editor names."""
        from .lcf import LcfFile
        from .script import _ce_names, common_event_names, read_function_names

        text = self._script_text(self.common_events_script, scriptfiles.COMMON_EVENTS)
        keep = read_function_names(text) if text is not None else {}
        assert self._ctx is not None
        names = {**{n: fname for n, fname in keep.items()}, **_ce_names(LcfFile.load(self.ldb_path).root, self._ctx)}
        return common_event_names(names, keep)

    def choice_separator(self) -> str | None:
        """Detected once per game, then kept in .rpgsync/config.json."""
        cfg = self._load_config()
        if "choice_separator" not in cfg:
            from .script import detect_choice_sep

            cfg["choice_separator"] = detect_choice_sep(self.map_paths().values())
            self._store_config(cfg)
        return cfg["choice_separator"]

    def map_names(self) -> dict[int, str]:
        """Map id -> name in the map tree (not the root: the game's title)."""
        stat = _stat(self.lmt_path)
        if stat is None:
            return {}
        if stat != self._map_names[0]:
            try:
                self._map_names = (stat, read_map_tree_names(self.lmt_path))
            except (OSError, LcfError):
                pass  # being written by the editor: the names read before
        return {k: v.decode(self.encoding, errors="replace") for k, v in self._map_names[1].items() if k != 0}
