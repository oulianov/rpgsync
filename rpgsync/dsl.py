"""The event script language of rpgsync: typed and documented vocabulary.

Every script starts with ``from rpgsync.dsl import *``.  rpgsync *parses*
scripts and never runs them, so nothing here does anything at runtime: the
classes and signatures exist so that editors autocomplete, show these docs
on hover, and type checkers (ty, pyright) flag wrong values while you type.

Example::

    @event(9, "Guard", x=10, y=5)
    def guard():
        @page(sprite=("Actor1", 3), layer="same")
        def page_1():
            text("Halt!")
            if variables[1] >= variables[2]:
                party.gold -= 100
            match show_choices("Pay", "Leave"):
                case "Pay":
                    switches[4] = True
                case "Leave":
                    this.move(move_away_from_player, frequency=6)
                    return

        @page(when=switches[4], sprite=("Actor1", 3), layer="same")
        def page_2():
            text("Welcome back.")

Conventions:

* Ranges use Python slices: ``variables[1:11]`` is variables 1 to 10.
* Most numbers can also be given as ``variables[id]`` (the value is read
  when the command runs).
* ``extra=(...)`` keeps raw parameters added by newer editor versions or
  patches; ``some_field=None`` marks a parameter that older editors did not
  write.  Both are generated by rpgsync to keep data byte-identical; you
  rarely need them yourself.
* Python ``#`` comments on their own line are stored as RPG Maker comments.
"""

