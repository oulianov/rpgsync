class Character:
    """A character on the map: ``this``, ``player``, ``events[id]``, vehicles."""

    map_id: Value
    x: Value
    y: Value
    direction: Value
    screen_x: Value
    screen_y: Value
    facing: Direction
    """Test with ``this.facing == "up"``."""

    def move(self, *steps: MoveStep, frequency: Frequency = 6, repeat: bool = False, skippable: bool = False) -> None:
        """Move Event: give the character a route to follow.

        Between ``jump_start`` and ``jump_end`` only movement steps count.
        Speed can only change relative to the current one (speed_up /
        speed_down).

        Args:
            steps: the route, e.g. ``move_up * 3, face_left``.
            frequency: 1 (slow) to 8 (continuous); affects moving, turning and waiting.
            repeat: loop the route forever.
            skippable: skip steps that cannot be done (blocked) instead of waiting.
        """

    def set_location(self, x: Number, y: Number, direction: TeleportDirection = "retain") -> None:
        """Set Event Location: move this event instantly.  x and y are both
        numbers or both variables[id]."""

    def show_animation(self, animation: int, wait: bool = False, whole_map: bool = False) -> None:
        """Show Battle Animation on this character (also works outside battle).

        Args:
            animation: animation id of the database.
            wait: wait until the animation ends.
            whole_map: play it over the whole screen instead of the character.
        """

    def call(self, page: Number) -> None:
        """Call Event: run one page of this map event and wait for it."""

    def flash(
        self,
        red: int | None = None,
        green: int | None = None,
        blue: int | None = None,
        strength: int | None = None,
        duration: float | None = None,
        wait: bool | None = None,
        extra: Extra = (),
    ) -> None:
        """Flash the character with a colour.

        Args:
            red, green, blue: colour, 0-31 each (default 31).
            strength: 0-31 (default 31).
            duration: seconds, in steps of 0.1 (default 0.5).
            wait: wait until the flash ends.
        """


