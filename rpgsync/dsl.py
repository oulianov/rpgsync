class Condition:
    """Something an ``if`` or ``@page(when=...)`` can test."""

    def __bool__(self) -> bool: ...


class Value:
    """A number read from the game when the command runs (a variable, a
    stat, the gold...).  Compare it to get a condition:
    ``variables[1] >= 10``, ``variables[1] == variables[2]``."""

    def __eq__(self, other: object) -> Condition: ...  # type: ignore[override]
    def __ne__(self, other: object) -> Condition: ...  # type: ignore[override]
    def __lt__(self, other: int | Value) -> Condition: ...
    def __le__(self, other: int | Value) -> Condition: ...
    def __gt__(self, other: int | Value) -> Condition: ...
    def __ge__(self, other: int | Value) -> Condition: ...
    def __neg__(self) -> Value: ...
    def __pos__(self) -> Value: ...


Number = int | Value
"""A number, or a value read from the game such as ``variables[3]``."""


class Counter(Value):
    """A value changed with ``+=`` / ``-=`` (gold, item counts)."""

    def __iadd__(self, amount: Number) -> Counter: ...
    def __isub__(self, amount: Number) -> Counter: ...


class Variable(Value):
    """One game variable, ``variables[id]``.

    Assign with ``=``, change with ``+= -= *= //= %=`` (``%`` is the
    remainder: 1953 % 100 = 53).  Values range from -9999999 to 9999999 in
    RPG Maker 2003 (-999999 to 999999 in 2000)."""

    def __iadd__(self, value: Number) -> Variable: ...
    def __isub__(self, value: Number) -> Variable: ...
    def __imul__(self, value: Number) -> Variable: ...
    def __ifloordiv__(self, value: Number) -> Variable: ...
    def __imod__(self, value: Number) -> Variable: ...


class VariableRange:
    """``variables[first:last+1]``: the same operation on every variable of the range."""

    def __iadd__(self, value: Number) -> VariableRange: ...
    def __isub__(self, value: Number) -> VariableRange: ...
    def __imul__(self, value: Number) -> VariableRange: ...
    def __ifloordiv__(self, value: Number) -> VariableRange: ...
    def __imod__(self, value: Number) -> VariableRange: ...


class Variables:
    """All game variables: ``variables[5]``, ``variables[1:11]`` (1 to 10),
    ``variables[variables[3]]`` (the variable whose id is stored in variable 3)."""

    @overload
    def __getitem__(self, key: int | Variable) -> Variable: ...
    @overload
    def __getitem__(self, key: slice) -> VariableRange: ...
    def __getitem__(self, key): ...
    def __setitem__(self, key: int | Variable | slice, value: Number | VariableRange | Variable) -> None: ...


class Switch(Condition):
    """One game switch, ``switches[id]`` (ON/OFF).  Set it with ``= True`` /
    ``= False``, test it with ``if switches[id]:`` or ``if not switches[id]:``."""

    def toggle(self) -> None:
        """Flip the switch: ON becomes OFF and OFF becomes ON."""


class SwitchRange:
    """``switches[first:last+1]``: several switches at once."""

    def toggle(self) -> None:
        """Flip every switch of the range."""


class Switches:
    """All game switches: ``switches[5]``, ``switches[1:11]`` (1 to 10),
    ``switches[variables[3]]`` (the switch whose id is in variable 3)."""

    @overload
    def __getitem__(self, key: int | Variable) -> Switch: ...
    @overload
    def __getitem__(self, key: slice) -> SwitchRange: ...
    def __getitem__(self, key): ...
    def __setitem__(self, key: int | Variable | slice, value: bool) -> None: ...


class Item:
    """``items[id]``: an item of the database.  ``items[3].count += 2`` gives
    two, ``if items[3] in party:`` tests possession.  The inventory is sorted
    by item id."""

    count: Counter
    """How many the party holds."""
    equipped: Value
    """How many are currently equipped by party members."""


class Items:
    def __getitem__(self, key: int | Variable) -> Item: ...


